block lock_uses_replaced_vendor_source_material:
  let tmp = getTempDir() / "bau-test-lock-source-replace"
  if dirExists(tmp):
    removeDir(tmp)
  defer:
    if dirExists(tmp):
      removeDir(tmp)

  write(tmp / "vendor" / "regpkg" / "regpkg.nimble", """
version = "2.0.0"
""")
  write(tmp / "vendor" / "regpkg" / "src" / "regpkg.nim",
    "const regpkg* = 2\n")

  var cfg = initBauConfig()
  cfg.deps["regpkg"] = DepInfo(version: some(">=1.0"),
    registry: some("mirror"))
  cfg.sources["mirror"] = SourceInfo(
    registry: "https://example.com/index",
    replaceWith: "vendor")
  cfg.sources["vendor"] = SourceInfo(directory: "vendor")

  let lockFile = generateLockFile(cfg, tmp)
  let pkg = lockFile.findPackage("regpkg").get()
  doAssert pkg.materialized
  doAssert pkg.id.version == "2.0.0"
  doAssert pkg.id.source == "vendor+vendor"
  doAssert pkg.path == "vendor/regpkg"
  doAssert unresolvedLockEntries(cfg, lockFile, tmp).len == 0

  let req = lockFile.rootDependencies[0]
  doAssert req.source == "vendor+vendor"

  let lockPath = tmp / LockFileName
  writeLockFile(lockFile, lockPath)
  doAssert lockIsValid(cfg, lockPath, tmp)
